/// Vendor marks, traced from the official vector files into normalised paths.
///
/// Each shape draws inside a unit square and is scaled to whatever frame it is
/// given, so one definition serves the 11 pt sidebar glyph and the 24 pt header
/// alike. Coordinates were converted offline rather than parsed at runtime: an
/// SVG parser would be a lot of surface area for artwork that never changes.
enum VendorMarkGeometry {
    static func point(_ rect: CGRect, _ x: CGFloat, _ y: CGFloat) -> CGPoint {
        CGPoint(x: rect.minX + x * rect.width, y: rect.minY + y * rect.height)
    }
}

