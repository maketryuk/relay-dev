/// Gemini's four-point spark.
///
/// Constructed rather than traced: the shape is exactly four quarter-circle
/// arcs, each centred on a corner of the bounding square with radius half its
/// side, so describing it in geometry is both shorter and exact.
public struct GeminiMarkShape: Shape {
    public init() {}

    public func path(in rect: CGRect) -> Path {
        let side = min(rect.width, rect.height)
        let box = CGRect(
            x: rect.midX - side / 2,
            y: rect.midY - side / 2,
            width: side,
            height: side
        )
        func p(_ x: CGFloat, _ y: CGFloat) -> CGPoint { VendorMarkGeometry.point(box, x, y) }

        // Cubic approximation of a 90-degree arc: 4/3 * tan(45/2) * radius.
        let pull: CGFloat = 0.27614

        var path = Path()
        path.move(to: p(0.5, 0))
        path.addCurve(to: p(1, 0.5), control1: p(0.5, pull), control2: p(1 - pull, 0.5))
        path.addCurve(to: p(0.5, 1), control1: p(1 - pull, 0.5), control2: p(0.5, 1 - pull))
        path.addCurve(to: p(0, 0.5), control1: p(0.5, 1 - pull), control2: p(pull, 0.5))
        path.addCurve(to: p(0.5, 0), control1: p(pull, 0.5), control2: p(0.5, pull))
        path.closeSubpath()
        return path
    }
}
